"""Write src/chartpal.h (RGB565 table) from tile-relay/relay/render.py COLOURS."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..'))
from relay.render import COLOURS
def c565(r, g, b): return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
out = os.path.join(here, '..', '..', 'src', 'chartpal.h')
with open(out, 'w') as f:
    f.write('// Generated by tile-relay/tools/gen_palette.py - do not edit.\n#pragma once\n#include <stdint.h>\n')
    f.write('static const uint16_t CHART_PAL[16] = {%s};\n' % ', '.join('0x%04X' % c565(*c) for c in COLOURS + [(0, 0, 0)] * (16 - len(COLOURS))))
print('wrote', out)
